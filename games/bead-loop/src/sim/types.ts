/**
 * Simulation constants and state layout shared by both backends.
 * MUST match rust/crates/bead-loop/src/sim.rs (WasmSim verifies at load).
 */
export const K = 9; // beads per block (3x3)
export const MAX_TUBES = 6;
export const MAX_CAP = 8;
export const MAX_BEADS = MAX_CAP * K;
export const QCAP = 128;
export const MAX_SLOTS = 320;
export const EMPTY = 255;
export const FALL_TIME = 0.3;
export const JAM_TIME = 3.0;
export const QUEUE_TAP_LIMIT = K;
export const MAX_EVENTS = 256;
export const NSCAL = 12;

export const EV = { ABSORB: 1, LAND: 2, EJECT: 3, DENY: 4, COMPLETE: 5, WIN: 6, LOSE: 7 } as const;
export const S = { OFFSET: 0, TIME: 1, ELAPSED: 2, JAM: 3, WON: 4, LOST: 5, TAPS: 6, STARTED: 7, FREE: 8 } as const;

/** One level as stored in levels.json (generated by the Rust tool). */
export interface LevelData {
  n: number;
  colors: number;
  cap: number;
  slots: number;
  speed: number;
  par: number;
  /** Block colours per tube, bottom → top, as digits. */
  tubes: string[];
  /** Belt slots: '.' empty or a colour digit. */
  belt: string;
}

/** Struct-of-arrays state; for wasm these are views into wasm memory. */
export interface SimState {
  nSlots: number;
  nTubes: number;
  cap: number;
  scal: Float64Array;
  slotColor: Uint8Array;
  slotBorn: Float64Array;
  tubeShell: Uint8Array;
  tubeBeads: Uint8Array;
  tubeLen: Uint16Array;
  fallT: Float64Array;
  fallLen: Uint16Array;
  queue: Uint8Array;
  qHead: Uint16Array;
  qLen: Uint16Array;
  shake: Float64Array;
  flash: Float64Array;
  complete: Uint8Array;
  combo: Uint16Array;
  events: Uint8Array;
  /** x, y per slot, filled by computePositions(). */
  pos: Float32Array;
}

export interface Sim {
  readonly backend: 'wasm' | 'ts';
  readonly s: SimState;
  init(level: LevelData): void;
  setPort(tube: number, frac: number): void;
  tap(tube: number): boolean;
  update(dt: number): void;
  eventCount(): number;
  clearEvents(): void;
  setPath(x: number, y: number, w: number, h: number, r: number, jitter: number): void;
  computePositions(): void;
  checksum(): number;
}

// ---- read helpers (backend-independent) ----
export const intake = (s: SimState, t: number): number => {
  const len = s.tubeLen[t];
  return len === 0 ? s.tubeShell[t] : s.tubeBeads[t * MAX_BEADS + len - 1];
};
export const beadAt = (s: SimState, t: number, j: number): number => s.tubeBeads[t * MAX_BEADS + j];
export const queueAt = (s: SimState, t: number, k: number): number => s.queue[t * QCAP + ((s.qHead[t] + k) % QCAP)];
export const hasWrong = (s: SimState, t: number): boolean => {
  for (let j = 0; j < s.tubeLen[t]; j++) if (beadAt(s, t, j) !== s.tubeShell[t]) return true;
  return false;
};

export function emptyState(): SimState {
  return {
    nSlots: 0, nTubes: 0, cap: 0,
    scal: new Float64Array(NSCAL),
    slotColor: new Uint8Array(MAX_SLOTS).fill(EMPTY),
    slotBorn: new Float64Array(MAX_SLOTS).fill(-1),
    tubeShell: new Uint8Array(MAX_TUBES),
    tubeBeads: new Uint8Array(MAX_TUBES * MAX_BEADS).fill(EMPTY),
    tubeLen: new Uint16Array(MAX_TUBES),
    fallT: new Float64Array(MAX_TUBES * MAX_BEADS),
    fallLen: new Uint16Array(MAX_TUBES),
    queue: new Uint8Array(MAX_TUBES * QCAP).fill(EMPTY),
    qHead: new Uint16Array(MAX_TUBES),
    qLen: new Uint16Array(MAX_TUBES),
    shake: new Float64Array(MAX_TUBES),
    flash: new Float64Array(MAX_TUBES),
    complete: new Uint8Array(MAX_TUBES),
    combo: new Uint16Array(MAX_TUBES),
    events: new Uint8Array(MAX_EVENTS * 2),
    pos: new Float32Array(MAX_SLOTS * 2),
  };
}
